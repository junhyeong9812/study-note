def josa(b, j):
    if not j: return b
    last = [c for c in b if '가' <= c <= '힣']
    if not last:  # 영어로 끝나면 받침 없는 것으로 본다(probe, 스큐 등은 규칙에서 따로 지정)
        return b + PAIR[j][1] if j not in ('으로', '로') else b + '로'
    code = (ord(last[-1]) - 0xAC00) % 28; has = code != 0
    if j in ('으로', '로'): return b + ('으로' if has and code != 8 else '로')
    return b + PAIR[j][0 if has else 1]
